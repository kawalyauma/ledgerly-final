import { readdir, readFile, writeFile, access } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modulesDir = path.join(root, "modules");
const entries = (await readdir(modulesDir, { withFileTypes: true }))
  .filter(entry => entry.isDirectory() && !entry.name.startsWith("_") && !entry.name.startsWith("."))
  .map(entry => entry.name)
  .sort();

const backendModules = [];
const catalog = [];
const seenKeys = new Set();
for (const name of entries) {
  const manifestPath = path.join(modulesDir, name, "module.json");
  try {
    const raw = JSON.parse(await readFile(manifestPath, "utf8"));
    if (!raw.key || !raw.name || !raw.version) throw new Error("key, name and version are required");
    if (raw.key !== name && raw.key !== "school-management" && name !== "ledgerly") {
      throw new Error(`module key '${raw.key}' should match folder '${name}'`);
    }
    if (seenKeys.has(raw.key)) throw new Error(`duplicate module key '${raw.key}'`);
    seenKeys.add(raw.key);
    catalog.push({
      key: String(raw.key),
      name: String(raw.name),
      version: String(raw.version),
      description: String(raw.description || `${raw.name} module.`),
      category: String(raw.category || "business"),
      core: Boolean(raw.core),
      active: raw.active !== false,
      manifest: raw.manifest && typeof raw.manifest === "object" ? raw.manifest : {},
    });
  } catch (error) {
    throw new Error(`Module '${name}' is missing or has an invalid module.json: ${error.message}`);
  }
  const backendEntry = path.join(modulesDir, name, "backend", "module.ts");
  try {
    await access(backendEntry);
    backendModules.push(name);
  } catch {
    // Frontend-only modules are allowed.
  }
}

const imports = backendModules.map((name, index) => `import { moduleDefinition as module${index} } from "./${name}/backend/module";`).join("\n");
const array = backendModules.map((_, index) => `module${index}`).join(", ");
const registry = `// AUTO-GENERATED by scripts/sync-modules.mjs. Do not edit by hand.\n${imports}\n\nexport const backendModules = [${array}].sort((a,b)=>(a.order ?? 100)-(b.order ?? 100)||a.name.localeCompare(b.name));\n`;
await writeFile(path.join(modulesDir, "backend-registry.generated.ts"), registry);

const catalogText = `// AUTO-GENERATED by scripts/sync-modules.mjs. Do not edit by hand.\nexport const moduleCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n`;
await writeFile(path.join(modulesDir, "catalog.generated.ts"), catalogText);

console.log(`Synced ${catalog.length} module manifest(s); ${backendModules.length} backend module(s).`);
